CREATE TABLE IF NOT EXISTS sie_schema_migrations (
    version INTEGER PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS transcription_corrections (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incorrect_text VARCHAR(500) NOT NULL CHECK (length(incorrect_text) > 0),
    correct_text VARCHAR(500) NOT NULL,
    case_sensitive BOOLEAN NOT NULL DEFAULT FALSE,
    priority INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    notes VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS transcription_corrections_active_priority
    ON transcription_corrections (is_active, priority DESC, id);

CREATE TABLE IF NOT EXISTS postprocessing_settings (
    id BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (id),
    filters JSONB NOT NULL DEFAULT '{}',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO postprocessing_settings (id) VALUES (TRUE) ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS transcription_correction_usage (
    correction_id INTEGER PRIMARY KEY REFERENCES transcription_corrections(id),
    usage_count BIGINT NOT NULL DEFAULT 0,
    last_used_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS dictation_history (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    raw_text TEXT NOT NULL,
    corrected_text TEXT NOT NULL,
    model_name TEXT NOT NULL,
    duration_ms BIGINT NOT NULL,
    delivered BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

